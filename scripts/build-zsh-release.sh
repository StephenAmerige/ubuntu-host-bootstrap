#!/usr/bin/env bash
# Build the ready-to-extract Zsh configuration distribution.
set -euo pipefail

if (( $# != 2 )) || [[ ! $1 =~ ^v[0-9]+\.[0-9]+\.[0-9]+$ ]]; then
   printf 'Usage: %s vMAJOR.MINOR.PATCH OUTPUT_DIRECTORY\n' "$0" >&2
   exit 2
fi

Version=$1
OutDir=$2
RepoRoot=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd -P)
mkdir -p -- "$OutDir"
OutDir=$(cd -- "$OutDir" && pwd -P)
WorkDir=$(mktemp -d)
trap 'rm -rf -- "$WorkDir"' EXIT

cd -- "$RepoRoot/files/zsh"
shopt -s nullglob
Files=(.zshenv .zshrc .zshrc.d/[0-9]*.zsh .zshrc.d/examples/*.zsh)

for File in "${Files[@]}"; do
   [[ -f $File && ! -L $File ]] || {
      printf 'Invalid Zsh source file: %s\n' "$File" >&2
      exit 1
   }
   mkdir -p -- "$WorkDir/stage/$(dirname -- "$File")"
   cp -- "$File" "$WorkDir/stage/$File"
done

[[ -f $WorkDir/stage/.zshrc.d/00-version.zsh ]] || {
   printf 'Missing release version module\n' >&2
   exit 1
}

cat > "$WorkDir/stage/.zshrc.d/00-version.zsh" <<VERSION
# Generated by scripts/build-zsh-release.sh for GitHub Release $Version.
typeset -g _ZshFilesVersion=$Version
VERSION

# Fixed timestamps and no ZIP extra fields make repeated builds of the
# same source/tag deterministic, while preserving the intentional order.
find "$WorkDir/stage" -type f -exec touch -t 202001010000 {} +
rm -f -- "$OutDir/zshfiles.zip" "$OutDir/zshfiles.zip.sha256"
(
   cd -- "$WorkDir/stage"
   TZ=UTC zip -X -q -9 "$OutDir/zshfiles.zip" "${Files[@]}"
)
(
   cd -- "$OutDir"
   sha256sum zshfiles.zip > zshfiles.zip.sha256
)

printf 'Created %s and its SHA-256 checksum for %s\n' "$OutDir/zshfiles.zip" "$Version"
